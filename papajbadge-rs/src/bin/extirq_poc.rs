//! Proof of concept: external (peripheral) interrupts are not dispatched with
//! ch58x-hal + qingke-rt 0.5.
//!
//! qingke-rt 0.5 uses the hardware vector table (mtvec "vectored, absolute address" mode):
//! on interrupt N the CPU jumps to the address stored at `mtvec_base + 4 * N`. The entries
//! for N >= 16 are expected in the `.vector_table.external_interrupts` linker section, but
//! the ch58x PAC leaves `__EXTERNAL_INTERRUPTS` in `.rodata`.
//!
//! The test pends the GPIOA interrupt (IRQ 17) from software. No pin flag is set, so the
//! HAL's GPIOA handler would simply return. If the last line printed is "pending IRQ 17",
//! the CPU never came back.
//!
//! Run: `cargo run --release --bin extirq_poc`, UART0 on PB7 at 115200.

#![no_std]
#![no_main]

use ch58x_hal as hal;
use hal::uart::UartTx;
use papajbadge_rs::log;
use papajbadge_rs::logger::init as init_logger;

const GPIOA_IRQ: u8 = 17;
const VECTOR_BASE: usize = 0x2000_0000; // mtvec base with the `highcode` feature

extern "C" {
    /// Interrupt entry stub generated by `#[qingke_rt::interrupt] fn GPIOA()` in ch58x-hal.
    fn GPIOA();
    fn DefaultInterruptHandler();
    static __EXTERNAL_INTERRUPTS: [usize; 36];
}

fn settle() {
    // let the UART shift out everything before we possibly hang
    for _ in 0..600_000 {
        unsafe { core::arch::asm!("nop") };
    }
}

#[qingke_rt::entry]
fn main() -> ! {
    let mut config = hal::Config::default();
    config.clock.use_pll_60mhz();
    let p = hal::init(config);
    let serial = UartTx::new(p.UART0, p.PB7, Default::default()).unwrap();
    init_logger(serial);

    let mtvec: usize;
    unsafe { core::arch::asm!("csrr {}, mtvec", out(reg) mtvec) };
    let slot = (VECTOR_BASE + 4 * GPIOA_IRQ as usize) as *const usize;
    let in_table = unsafe { slot.read_volatile() };
    let pac_table = &raw const __EXTERNAL_INTERRUPTS;

    log!("\n=== external interrupt dispatch PoC ===");
    log!("mtvec                            = {:#010x}", mtvec);
    log!("GPIOA handler (HAL)              = {:#010x}", GPIOA as *const () as usize);
    log!("DefaultInterruptHandler          = {:#010x}", DefaultInterruptHandler as *const () as usize);
    log!("hardware vector slot for IRQ 17  = {:#010x} (at {:#010x})", in_table, slot as usize);
    log!("PAC __EXTERNAL_INTERRUPTS lives at {:#010x}, its entry 17 = {:#010x}", pac_table as usize, unsafe {
        (*pac_table)[GPIOA_IRQ as usize]
    });

    log!("pending IRQ 17 (GPIOA)...");
    settle();
    unsafe {
        qingke::pfic::enable_interrupt(GPIOA_IRQ);
        qingke::pfic::pend_interrupt(GPIOA_IRQ);
    }
    settle();
    log!("handler returned: external interrupts work");

    loop {
        unsafe { core::arch::asm!("nop") };
    }
}
